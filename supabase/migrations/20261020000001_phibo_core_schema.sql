-- Políticas para phibo_vendas
DROP POLICY IF EXISTS "phibo_vendas_view_policy" ON public.phibo_vendas;
CREATE POLICY "phibo_vendas_view_policy" ON public.phibo_vendas
FOR SELECT TO authenticated
USING (
    public.phibo_get_auth_role() = 'super_admin'
    OR (
        cliente_id = public.phibo_get_auth_cliente_id()
        AND (
            public.phibo_get_auth_role() IN ('admin', 'manager')
            OR (
                public.phibo_get_auth_role() = 'seller'
                AND vendedor = (SELECT nome_vendedor FROM public.phibo_perfis WHERE id = auth.uid())
            )
        )
    )
);

