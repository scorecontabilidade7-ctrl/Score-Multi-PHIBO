-- =====================================================================================
-- 8. TRIGGER AUTOMÁTICO DE CRIAÇÃO DE PERFIL VIA SUPABASE AUTH
-- =====================================================================================
CREATE OR REPLACE FUNCTION public.phibo_handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.phibo_perfis (id, full_name, email, role, cliente_id, nome_vendedor)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'role', 'seller'),
        NULLIF(NEW.raw_user_meta_data->>'cliente_id', '')::UUID,
        NEW.raw_user_meta_data->>'nome_vendedor'
    )
    ON CONFLICT (id) DO UPDATE
    SET full_name = EXCLUDED.full_name,
        updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created_phibo ON auth.users;
CREATE TRIGGER on_auth_user_created_phibo
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.phibo_handle_new_user();

-- =====================================================================================
-- 9. FUNÇÕES DE SUPORTE AO RLS (SEM RECURSÃO)
-- =====================================================================================
CREATE OR REPLACE FUNCTION public.phibo_get_auth_role()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT role FROM public.phibo_perfis WHERE id = auth.uid() LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.phibo_get_auth_cliente_id()
RETURNS UUID
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT cliente_id FROM public.phibo_perfis WHERE id = auth.uid() LIMIT 1;
$$;

