-- Políticas para phibo_perfis (Usuário sempre lê seu próprio perfil sem recursão)
DROP POLICY IF EXISTS "phibo_perfis_select_policy" ON public.phibo_perfis;
CREATE POLICY "phibo_perfis_select_policy" ON public.phibo_perfis
FOR SELECT TO authenticated
USING (
    id = auth.uid() 
    OR public.phibo_get_auth_role() = 'super_admin'
    OR (
        cliente_id = public.phibo_get_auth_cliente_id() 
        AND public.phibo_get_auth_role() = 'admin'
    )
);

DROP POLICY IF EXISTS "phibo_perfis_update_policy" ON public.phibo_perfis;
CREATE POLICY "phibo_perfis_update_policy" ON public.phibo_perfis
FOR UPDATE TO authenticated
USING (
    id = auth.uid() 
    OR public.phibo_get_auth_role() = 'super_admin'
);

