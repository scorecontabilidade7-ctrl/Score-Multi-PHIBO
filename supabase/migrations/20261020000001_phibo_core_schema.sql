    meta_top2 NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    meta_master NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    perc_minima NUMERIC(5,2) NOT NULL DEFAULT 1.00,
    perc_top1 NUMERIC(5,2) NOT NULL DEFAULT 1.50,
    perc_top2 NUMERIC(5,2) NOT NULL DEFAULT 2.00,
