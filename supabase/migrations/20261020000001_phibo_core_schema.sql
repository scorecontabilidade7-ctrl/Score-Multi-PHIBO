-- =====================================================================================
-- 2. TABELA: phibo_vendas (Tabela Fato de Vendas e Atendimentos)
-- =====================================================================================
CREATE TABLE IF NOT EXISTS public.phibo_vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id UUID NOT NULL REFERENCES public.phibo_clientes_config(id) ON DELETE CASCADE,
    origem VARCHAR(100) DEFAULT 'Loja Física',
    data_venda DATE NOT NULL,
    hora_venda TIME NOT NULL DEFAULT '00:00:00',
    cliente_nome VARCHAR(255),
    cliente_telefone VARCHAR(50),
    cliente_completo TEXT,
    vendedor VARCHAR(150),
    quantidade INTEGER NOT NULL DEFAULT 1,
    sub_total NUMERIC(12,2) DEFAULT 0.00,
    desconto NUMERIC(12,2) DEFAULT 0.00,
    trocas NUMERIC(12,2) DEFAULT 0.00,
    cashback NUMERIC(12,2) DEFAULT 0.00,
    frete NUMERIC(12,2) DEFAULT 0.00,
    valor_total NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.phibo_vendas IS 'Registro analítico de cada cupom/venda importado do PHIBO.';

-- =====================================================================================
-- 3. TABELA: phibo_perfis (Controle de Usuários e Perfis de Acesso RBAC)
-- =====================================================================================
CREATE TABLE IF NOT EXISTS public.phibo_perfis (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    cliente_id UUID REFERENCES public.phibo_clientes_config(id) ON DELETE SET NULL,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'seller' CHECK (role IN ('super_admin', 'admin', 'manager', 'seller')),
    nome_vendedor TEXT,
    ativo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.phibo_perfis IS 'Perfis de usuários do sistema vinculados ao Supabase Auth com governança por loja.';

-- =====================================================================================
-- 4. TABELA: phibo_vendedores_config (Normalização de Nomes e Fotos)
-- =====================================================================================
CREATE TABLE IF NOT EXISTS public.phibo_vendedores_config (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cliente_id UUID NOT NULL REFERENCES public.phibo_clientes_config(id) ON DELETE CASCADE,
    nome_vendedor VARCHAR(150) NOT NULL,
    url_foto TEXT,
    peso_meta NUMERIC(4,2) NOT NULL DEFAULT 1.00,
    ativo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT unq_phibo_vendedor_cliente UNIQUE (cliente_id, nome_vendedor)
